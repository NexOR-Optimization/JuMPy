# Run the workload and C API tests in ordinary Julia processes first, using
# the same environment and Julia version as the image build:
#
# The project must resolve the patched JuMP and GenOpt checkouts documented in
# README.md, plus this JuMPyHiGHS package. From the repository root:
#
#   julia --project=/path/to/backend-environment --trace-dispatch=/tmp/workload.trace julia/workload.jl
#   julia --project=/path/to/backend-environment --trace-dispatch=/tmp/tests.trace julia/test/runtests.jl
#   julia --project=/path/to/backend-environment julia/generate_trim_dispatch.jl /tmp/workload.trace /tmp/tests.trace
#
# The generated file complements trim_roots.jl's finite operator/leaf roots.
# Trace coverage alone does not retain unexecuted branches or all combinations.
using JuMPyHiGHS
import GenOpt, HiGHS, JuMP, MathOptInterface

isempty(ARGS) && error("Pass one or more --trace-dispatch output files")
signatures = String[]
for path in ARGS
    in_workload = false
    for line in eachline(path)
        in_workload |= occursin("JuMPyHiGHS.jumpy_", line)
        in_workload || continue
        startswith(line, "precompile(Tuple{") || continue
        package_signature = occursin(r"JuMP|GenOpt|HiGHS|MathOptInterface|MutableArithmetics", line)
        collection_signature = occursin(
            r"typeof\(Base\.(?:_array_for(?:_inner)?|iterate|length|eachindex|axes|first|all|_all|setindex!|getindex)\)|Type\{Base\.(?:IteratorSize|LinearIndices)",
            line,
        ) && occursin(r"Array\{(?:Any|Real|Float64|Int64)|(?:UnitRange|OneTo)\{Int64\}", line)
        package_signature || collection_signature || continue
        occursin(r"Main\.|Test\.|Base\.Compiler|CachingOptimizer|\.Bridges\.", line) && continue
        line = replace(line, "MutableArithmetics." => "JuMP._MA.")
        expression = Meta.parse(line)
        # Check that private/generated names still resolve against these exact
        # dependency versions before producing the build input.
        signature = Core.eval(Main, expression.args[2])
        signature <: Tuple || error("Not a dispatch signature: $line")
        push!(signatures, replace(line, r"^precompile\(" => "Base.Experimental.entrypoint("))
    end
end
unique!(signatures)
open(joinpath(@__DIR__, "trim_dispatch.jl"), "w") do io
    println(io, "# Generated by generate_trim_dispatch.jl from ordinary Julia dispatch traces.")
    println(io, "# Regenerate with the same Julia version and dependency environment as the image.")
    println(io, "# Finite untraced combinations are registered separately in trim_roots.jl.")
    foreach(line -> println(io, line), signatures)
end
println("Wrote ", length(signatures), " supplementary roots to trim_dispatch.jl")
