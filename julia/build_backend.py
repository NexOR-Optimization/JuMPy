"""
Build a compiled JuMPy backend from its recipe, and package it for Python:

    python julia/build_backend.py RECIPE [--name NAME] [--wheel DIST]

RECIPE is the directory of a Julia package `JuMPy<Name>` whose module calls
`JuMPy.@entrypoints`, with a `workload.jl` script exercising its C ABI and,
optionally, a `roots.jl` script registering more compilation roots. See
`julia/README.md` and `julia/backends/` for examples. The steps are:

1. instantiate the recipe environment;
2. trace the dynamic dispatches of `workload.jl` in ordinary Julia;
3. turn them into compilation roots with `JuMPy.TrimDispatch`;
4. compile the recipe module with JuliaC into `RECIPE/build/bundle`, with
   `--trim=unsafe-warn`;
5. with `--wheel DIST`, build the platform wheel `jumpy-opt-NAME` into `DIST`,
   which contains this bundle in `jumpy/_backends/NAME` and, unless the
   `jumpy-opt` package that it requires has it, the module `jumpy/NAME.py`.

Julia, a C compiler and JuliaC (`julia --project=@juliac -m JuliaC`) must be
installed. The image is compiled for the CPU target `--cpu-target`, `generic`
by default for portable binaries; the other steps use the native target, so
that they reuse the package caches of the environment.
"""

import argparse
import os
import shutil
import subprocess
import sys
import tomllib

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import package_bundle  # noqa: E402

# The root of the JuMPy repository.
_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# The Python module of a backend, written into its wheel.
STUB = '''"""Compiled {package} backend: ``import jumpy.{name} as jp``.

Generated by JuMPy's julia/build_backend.py. Importing this module does not
initialize Julia.
"""

from jumpy import *  # Re-export the common modeling API.
from jumpy import _facade

_facade.install(globals(), "{name}")
'''

PYPROJECT = '''[build-system]
requires = ["hatchling"]
build-backend = "hatchling.build"

[project]
name = "jumpy-opt-{name}"
version = "{version}"
description = "The compiled {package} backend of JuMPy: import jumpy.{name}"
requires-python = ">=3.10"
dependencies = ["jumpy-opt>={jumpy_version}"]

[tool.hatch.build.targets.wheel]
packages = ["jumpy"]

[tool.hatch.build.targets.wheel.hooks.custom]
'''

# Tag the wheel with the platform of the bundle that package_bundle.py wrote.
HATCH_BUILD = '''from pathlib import Path

from hatchling.builders.hooks.plugin.interface import BuildHookInterface


class CustomBuildHook(BuildHookInterface):
    def initialize(self, version, build_data):
        tag = Path(self.root, "jumpy", "_backends", "{name}", "wheel-tag").read_text()
        build_data["pure_python"] = False
        build_data["tag"] = f"py3-none-{{tag.strip()}}"
'''


def _string(value):
    """A Julia string literal of `value`."""
    return 'raw"' + value.replace('"', '\\"') + '"'


def _julia(*args, project, cpu_target=None):
    command = ["julia", "--startup-file=no", f"--project={project}", *args]
    env = {k: v for k, v in os.environ.items() if k != "JULIA_CPU_TARGET"}
    if cpu_target is not None:
        env["JULIA_CPU_TARGET"] = cpu_target
    print("+", " ".join(command), flush=True)
    subprocess.run(command, check=True, env=env)


def _recipe(recipe):
    with open(os.path.join(recipe, "Project.toml"), "rb") as io:
        project = tomllib.load(io)
    module = project["name"]
    # Loaded to resolve the traced calls: the solver and its dependencies.
    deps = [dep for dep in project.get("deps", {}) if dep != "JuMPy"]
    return module, deps


def _default_name(module):
    if not module.startswith("JuMPy") or module == "JuMPy":
        raise ValueError(f"Expected a package named JuMPy<Name>, got {module}")
    return module[len("JuMPy"):].lower()


def build(recipe, name=None, traces=(), cpu_target="generic"):
    """Compile the image of `recipe` into `recipe/build/bundle` and return
    the bundle directory and the backend name."""
    recipe = os.path.abspath(recipe)
    module, deps = _recipe(recipe)
    name = name or _default_name(module)
    build_dir = os.path.join(recipe, "build")
    os.makedirs(build_dir, exist_ok=True)
    _julia("-e", "using Pkg; Pkg.instantiate()", project=recipe)

    scripts = [os.path.join(recipe, "workload.jl"), *map(os.path.abspath, traces)]
    trace_files = []
    for k, script in enumerate(scripts):
        trace = os.path.join(build_dir, f"{k}.trace")
        _julia(f"--trace-dispatch={trace}", script, project=recipe)
        trace_files.append(trace)

    dispatch = os.path.join(build_dir, "dispatch.jl")
    imports = "".join(f"import {dep}\n" for dep in deps)
    generate = (
        f"import JuMPy, {module}\n{imports}"
        f"JuMPy.TrimDispatch.generate({_string(dispatch)}, "
        f"[{', '.join(map(_string, trace_files))}], {module})\n"
    )
    _julia("-e", generate, project=recipe)

    entry = os.path.join(build_dir, "entry.jl")
    roots = os.path.join(recipe, "roots.jl")
    with open(entry, "w") as io:
        io.write("# Generated by julia/build_backend.py.\n")
        io.write(f"import JuMPy\nimport {module}\n\n")
        io.write("if Base.JLOptions().trim != 0\n")
        io.write(f"    JuMPy.add_trim_roots({module})\n")
        io.write(f"    JuMPy.TrimDispatch.add_roots({_string(dispatch)})\n")
        if os.path.exists(roots):
            io.write(f"    include({_string(roots)})\n")
        io.write("end\n")

    bundle = os.path.join(build_dir, "bundle")
    shutil.rmtree(bundle, ignore_errors=True)
    _julia(
        "-m", "JuliaC",
        "--output-lib", os.path.join(bundle, f"libjumpy_{name}"),
        "--project", recipe,
        "--compile-ccallable",
        "--trim=unsafe-warn",
        "--jl-option", "handle-signals=no",
        "--bundle", bundle,
        entry,
        project="@juliac",
        cpu_target=cpu_target,
    )
    return bundle, name


def wheel(bundle, name, dist, package_name, version):
    """Build the wheel `jumpy-opt-<name>` of `bundle` into `dist`."""
    project = os.path.join(os.path.dirname(bundle), "wheel")
    shutil.rmtree(project, ignore_errors=True)
    package_bundle.main(bundle, os.path.join(project, "jumpy", "_backends", name))
    # The modules of the backends of this repository, such as jumpy/highs.py,
    # are in jumpy-opt, which tells to install the wheel when it is missing.
    if not os.path.exists(os.path.join(_ROOT, "src", "jumpy", f"{name}.py")):
        with open(os.path.join(project, "jumpy", f"{name}.py"), "w") as io:
            io.write(STUB.format(name=name, package=package_name))
    with open(os.path.join(project, "pyproject.toml"), "w") as io:
        io.write(PYPROJECT.format(
            name=name,
            package=package_name,
            version=version,
            jumpy_version=_jumpy_version(),
        ))
    with open(os.path.join(project, "hatch_build.py"), "w") as io:
        io.write(HATCH_BUILD.format(name=name))
    command = ["uv", "build", "--wheel", "--out-dir", os.path.abspath(dist), project]
    print("+", " ".join(command), flush=True)
    subprocess.run(command, check=True)


def _jumpy_version():
    with open(os.path.join(_ROOT, "pyproject.toml"), "rb") as io:
        return tomllib.load(io)["project"]["version"]


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("recipe", help="directory of the JuMPy<Name> Julia package")
    parser.add_argument("--name", help="Python module name (default: <name> lowercase)")
    parser.add_argument(
        "--trace", action="append", default=[],
        help="additional script to trace in the recipe environment",
    )
    parser.add_argument("--wheel", metavar="DIST", help="build the jumpy-opt-<name> wheel")
    parser.add_argument(
        "--version", default=_jumpy_version(),
        help="version of the wheel (default: the version of jumpy-opt)",
    )
    parser.add_argument(
        "--cpu-target",
        default=os.environ.get("JULIA_CPU_TARGET", "generic"),
        help="JULIA_CPU_TARGET of the image (default: $JULIA_CPU_TARGET or generic)",
    )
    args = parser.parse_args(argv)
    bundle, name = build(args.recipe, args.name, args.trace, args.cpu_target)
    module, _ = _recipe(os.path.abspath(args.recipe))
    if args.wheel:
        wheel(bundle, name, args.wheel, module[len("JuMPy"):], args.version)


if __name__ == "__main__":
    main()
