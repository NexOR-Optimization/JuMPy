"""The module of a compiled backend, such as ``import jumpy.highs as jp``.

Each backend module, generated by julia/build_backend.py, re-exports the common
modeling API and calls :func:`install`. Importing it does not initialize Julia.
"""

from jumpy import __all__ as _common_all
from jumpy import backend
from jumpy._registry import Namespace, registry
from jumpy.model import Model as _Model


def install(namespace, name):
    """Define ``Model``, ``MOI`` and the other set modules, such as
    ``MathOptVRP``, in the namespace of the module jumpy.<name>."""
    MOI = Namespace(name, "MathOptInterface")

    class Model(_Model):
        def __init__(self):
            super().__init__(backend.JuliacOps(backend._load_lib(name), MOI))

    Model.__doc__ = f"A model using the compiled jumpy.{name} library."
    Model.__module__ = namespace["__name__"]

    def __getattr__(attribute):
        # The modules of the other sets of the registry, which loads the library.
        if not attribute.startswith("_") and attribute in registry(name):
            return Namespace(name, attribute)
        raise AttributeError(f"module {namespace['__name__']!r} has no attribute {attribute!r}")

    namespace.update(
        Model=Model,
        MOI=MOI,
        __getattr__=__getattr__,
        __all__=[*_common_all, "Model", "MOI"],
    )
